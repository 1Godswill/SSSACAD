/* Alerts: Friday register reminder, announcement rings, and the Admin "buzz all devices" button.
   (Window.Alerts / window.Reminder both point at the same object.)

   Friday register reminder.
   Every Friday at 12:00, 13:00 and 14:00 (the phone's own clock) the app rings a loud bell, shows
   "Please, update your register now" on a full-screen popup and says it aloud.

   How it behaves:
   - It works while the app is open (in front, or recently in the background). A web page cannot wake
     itself when it is fully closed - the Android app version (APK) covers that case, see APK-NOTES.md.
   - If the app is opened a few minutes after a slot (up to GRACE_MIN), the reminder still rings once.
   - Each slot rings only once per day on a device. Tapping "I'm updating it now" silences it.
   - The bell is generated by the phone (no sound file), so it works offline and adds no weight.
   - Browsers only allow sound after the person has tapped the screen once; teachers always do
     (to pick a class) so the sound is unlocked long before Friday noon. */
(function () {
  "use strict";

  const REMIND_DAY = 5;               // Friday (Sunday = 0)
  const REMIND_HOURS = [12, 13, 14];  // 12pm, 1pm, 2pm
  const GRACE_MIN = 15;               // still ring if the app is opened this late after a slot
  const MESSAGE = "Please, update your register now";
  const FIRED_KEY = "sssacad_reminder_fired";

  let ctx = null;          // Web Audio context
  let master = null;       // master volume of the bell currently ringing
  let ringTimers = [];
  let overlay = null;

  /* ---------- Sound ---------- */
  function getCtx() {
    if (!ctx) {
      const AC = window.AudioContext || window.webkitAudioContext;
      if (!AC) return null;
      try { ctx = new AC(); } catch (e) { return null; }
    }
    if (ctx.state === "suspended") { try { ctx.resume(); } catch (e) { /* needs a tap first */ } }
    return ctx;
  }

  // First tap anywhere unlocks sound for the rest of the session.
  function unlockAudio() {
    getCtx();
    ["pointerdown", "touchstart", "keydown"].forEach((ev) => window.removeEventListener(ev, unlockAudio, true));
  }
  ["pointerdown", "touchstart", "keydown"].forEach((ev) => window.addEventListener(ev, unlockAudio, true));

  // One bell strike: a handful of sine partials, each fading away, like a struck metal bell.
  function strike(c, out, when) {
    const base = 880;
    [[0.5, 1.0, 2.6], [1, 0.9, 2.2], [1.19, 0.5, 1.7], [1.56, 0.45, 1.3], [2, 0.5, 1.1], [2.51, 0.3, 0.8], [3.2, 0.25, 0.6], [4.1, 0.15, 0.4]]
      .forEach(([ratio, level, life]) => {
        const osc = c.createOscillator();
        const g = c.createGain();
        osc.type = "sine";
        osc.frequency.value = base * ratio;
        g.gain.setValueAtTime(0.0001, when);
        g.gain.exponentialRampToValueAtTime(level, when + 0.008);
        g.gain.exponentialRampToValueAtTime(0.0001, when + life);
        osc.connect(g); g.connect(out);
        osc.start(when); osc.stop(when + life + 0.05);
      });
  }

  function stopBell() {
    ringTimers.forEach(clearTimeout); ringTimers = [];
    if (master && ctx) {
      try { master.gain.cancelScheduledValues(ctx.currentTime); master.gain.setTargetAtTime(0, ctx.currentTime, 0.05); } catch (e) { /* ignore */ }
    }
    master = null;
    try { if (window.speechSynthesis) window.speechSynthesis.cancel(); } catch (e) { /* ignore */ }
    try { if (navigator.vibrate) navigator.vibrate(0); } catch (e) { /* ignore */ }
  }

  function ringBell(opts) {
    opts = opts || {};
    stopBell();
    const strikes = opts.strikes || 9, gap = opts.gap || 1.0;
    const c = getCtx();
    if (c) {
      const comp = c.createDynamicsCompressor(); // keeps it loud without crackling
      master = c.createGain();
      master.gain.value = 0.9;
      master.connect(comp); comp.connect(c.destination);
      const t0 = c.currentTime + 0.05;
      for (let i = 0; i < strikes; i++) strike(c, master, t0 + i * gap);
    }
    try { if (navigator.vibrate) navigator.vibrate(opts.vibrate || [400, 200, 400, 200, 400, 200, 400]); } catch (e) { /* ignore */ }
    if (opts.speak !== false) ringTimers.push(setTimeout(() => speak(opts.say), opts.noDelay ? 300 : 3200));
    if (opts.stopAfterMs) ringTimers.push(setTimeout(stopBell, opts.stopAfterMs)); // hard cut-off (used by the 3-second buzz)
  }

  function speak(text) {
    try {
      if (!window.speechSynthesis) return;
      const u = new SpeechSynthesisUtterance(text || MESSAGE);
      u.volume = 1; u.rate = 0.95; u.lang = "en-GB";
      window.speechSynthesis.cancel();
      window.speechSynthesis.speak(u);
    } catch (e) { /* ignore */ }
  }

  /* ---------- Popup ---------- */
  function escHtml(t) { return String(t == null ? "" : t).replace(/[&<>"']/g, (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[ch])); }

  // o: { icon, title, sub, body, done (button text), again (function that rings once more, optional) }
  function showPopup(o) {
    if (overlay) { overlay.remove(); overlay = null; } // a newer alert replaces an older one
    overlay = document.createElement("div");
    overlay.id = "registerReminder";
    overlay.className = "no-print no-caps";
    overlay.style.cssText = "position:fixed;inset:0;z-index:99999;background:rgba(10,20,40,.88);display:flex;align-items:center;justify-content:center;padding:20px;text-transform:none;";
    overlay.innerHTML = `
      <style>
        @keyframes rrShake{0%,100%{transform:rotate(0)}10%,30%,50%,70%,90%{transform:rotate(-14deg)}20%,40%,60%,80%{transform:rotate(14deg)}}
        #registerReminder .rr-bell{font-size:64px;display:inline-block;animation:rrShake 1.2s ease-in-out infinite;transform-origin:50% 10%;}
        #registerReminder *{text-transform:none !important;}
      </style>
      <div style="background:#fff;border-radius:20px;padding:26px 22px;max-width:360px;width:100%;max-height:90vh;overflow:auto;text-align:center;box-shadow:0 20px 60px rgba(0,0,0,.4);">
        <div class="rr-bell">${o.icon || "🔔"}</div>
        <img src="icons/logo.png" alt="" style="width:54px;height:54px;display:block;margin:6px auto 0;">
        <h2 style="margin:10px 0 6px;font-size:21px;color:#142544;">${escHtml(o.title)}</h2>
        ${o.sub ? `<p style="margin:0 0 10px;font-size:13px;color:#6b7688;">${escHtml(o.sub)}</p>` : ""}
        ${o.body ? `<div style="margin:0 0 16px;font-size:15px;color:#16233d;white-space:pre-wrap;text-align:left;background:#fdf1dd;border-left:4px solid #f2a93b;border-radius:8px;padding:10px 12px;">${escHtml(o.body)}</div>` : ""}
        <button id="rrDone" style="width:100%;background:#2f6feb;color:#fff;border:none;padding:13px;border-radius:12px;font-size:15px;font-weight:700;">${escHtml(o.done || "OK")}</button>
        ${o.again ? `<button id="rrRing" style="width:100%;background:#fff;color:#2f6feb;border:1px solid #2f6feb;padding:11px;border-radius:12px;font-size:13px;font-weight:600;margin-top:8px;">🔔 Ring again</button>` : ""}
      </div>`;
    document.body.appendChild(overlay);
    document.getElementById("rrDone").addEventListener("click", closePopup);
    if (o.again) document.getElementById("rrRing").addEventListener("click", o.again);
  }

  function closePopup() {
    stopBell();
    if (overlay) { overlay.remove(); overlay = null; }
  }

  function fridayPopup(slotLabel) {
    showPopup({ icon: "🔔", title: MESSAGE, sub: "Friday reminder · " + slotLabel + " — fill in this week's attendance and scores before the weekend.",
      done: "I'm updating it now", again: () => ringBell() });
  }

  function systemNotification(slotLabel) {
    try {
      if (!("Notification" in window) || Notification.permission !== "granted") return;
      const opts = { body: "Friday reminder · " + slotLabel, icon: "icons/icon-192.png", badge: "icons/icon-192.png",
        tag: "register-reminder", renotify: true, requireInteraction: true, vibrate: [400, 200, 400, 200, 400] };
      if (navigator.serviceWorker && navigator.serviceWorker.ready) {
        navigator.serviceWorker.ready.then((reg) => reg.showNotification(MESSAGE, opts)).catch(() => new Notification(MESSAGE, opts));
      } else new Notification(MESSAGE, opts);
    } catch (e) { /* ignore */ }
  }

  /* ---------- Schedule ---------- */
  function readFired() { try { return JSON.parse(localStorage.getItem(FIRED_KEY) || "[]"); } catch (e) { return []; } }
  function markFired(id) {
    try { localStorage.setItem(FIRED_KEY, JSON.stringify(readFired().filter((x) => x.slice(0, 10) === id.slice(0, 10)).concat(id))); } catch (e) { /* ignore */ }
  }
  function pad(n) { return String(n).padStart(2, "0"); }
  function label(h) { return (h % 12 || 12) + (h < 12 ? "am" : "pm"); }

  // Which slot (if any) is due right now?
  function dueSlot(now) {
    if (now.getDay() !== REMIND_DAY) return null;
    const mins = now.getHours() * 60 + now.getMinutes();
    const day = now.getFullYear() + "-" + pad(now.getMonth() + 1) + "-" + pad(now.getDate());
    const fired = readFired();
    for (let i = REMIND_HOURS.length - 1; i >= 0; i--) { // latest slot first
      const h = REMIND_HOURS[i], start = h * 60;
      if (mins >= start && mins < start + GRACE_MIN) {
        const id = day + "T" + pad(h);
        if (fired.indexOf(id) === -1) return { id: id, h: h };
      }
    }
    return null;
  }

  function check() {
    const slot = dueSlot(new Date());
    if (!slot) return;
    markFired(slot.id);
    fridayPopup(label(slot.h));
    ringBell();
    if (document.hidden) systemNotification(label(slot.h));
  }

  /* ---------- Admin card: test + notification permission ---------- */
  window.reminderCardHtml = function () {
    const perm = ("Notification" in window) ? Notification.permission : "unsupported";
    return `
    <div class="card">
      <h2>🔔 Friday Register Reminder</h2>
      <p style="font-size:12.5px;color:var(--muted);">Every Friday at 12pm, 1pm and 2pm the app rings a bell and says "${MESSAGE}" on every phone that has it open. Use the button to hear it now.</p>
      <button class="btn secondary" id="testReminderBtn">🔔 Test the bell now</button>
      ${perm === "default" ? `<button class="btn secondary" id="allowNotifyBtn">📲 Also show phone notifications</button>` : ""}
      ${perm === "denied" ? `<p style="font-size:12px;color:var(--muted);margin-top:8px;">Phone notifications are blocked for this app in the phone's settings.</p>` : ""}
    </div>${window.NativeAlerts ? window.NativeAlerts.cardHtml() : ""}`;
  };
  window.wireReminderCard = function (root) {
    if (window.NativeAlerts) window.NativeAlerts.wireCard(root);
    const t = root.querySelector("#testReminderBtn");
    if (t) t.addEventListener("click", () => { getCtx(); fridayPopup("test"); ringBell(); });
    const n = root.querySelector("#allowNotifyBtn");
    if (n) n.addEventListener("click", () => {
      try { Notification.requestPermission().then(() => { if (typeof renderAdminTab === "function") renderAdminTab(); }); } catch (e) { /* ignore */ }
    });
  };

  /* ---------- Admin buzz: ring every online device for 3 seconds ----------
     The admin's tap writes one small record ("buzz") into the shared sync data. Every device that is
     open and syncing (checks every ~20 seconds) sees a record it has not seen before and rings for
     3 seconds, with a popup showing the optional message. The admin's own phone does not ring. */
  const BUZZ_SEEN_KEY = "sssacad_buzz_seen";
  const BUZZ_FRESH_MS = 10 * 60 * 1000; // an old buzz is ignored by a device that was offline / just installed
  function lsGet(k) { try { return localStorage.getItem(k); } catch (e) { return null; } }
  function lsSet(k, v) { try { localStorage.setItem(k, v); } catch (e) { /* ignore */ } }

  function ringBuzz(text) {
    getCtx();
    showPopup({ icon: "📣", title: "Reminder from Admin", body: text || "Please check the app.", done: "OK" });
    ringBell({ strikes: 4, gap: 0.75, speak: false, vibrate: [3000], stopAfterMs: 3000 });
  }

  function sendBuzz(text) {
    if (typeof Sync === "undefined" || !Sync.isConfigured()) return { ok: false, why: "Set up Sync first (Sync Across Devices, lower in Admin)" };
    if (typeof saveBuzz !== "function") return { ok: false, why: "Buzz is not available" };
    const id = newId();
    saveBuzz({ sig: [id, Date.now(), getDeviceId(), String(text || "").trim()] });
    lsSet(BUZZ_SEEN_KEY, id);          // this phone does not ring itself
    Sync.syncNow({ force: true });
    return { ok: true };
  }

  function receiveBuzz() {
    if (typeof loadBuzz !== "function") return;
    const sig = (loadBuzz() || {}).sig;
    if (!Array.isArray(sig) || !sig[0]) return;
    const id = sig[0], at = Number(sig[1]) || 0, by = sig[2], text = sig[3] || "";
    const seen = lsGet(BUZZ_SEEN_KEY);
    if (seen === id) return;
    lsSet(BUZZ_SEEN_KEY, id);
    if (seen === null) return;                                  // first time this device sees the feature: stay quiet
    if (by === getDeviceId()) return;                           // sent from this phone
    if (Math.abs(Date.now() - at) > BUZZ_FRESH_MS) return;      // too old to matter
    ringBuzz(text);
  }

  /* ---------- Announcements ring the phone ----------
     A new or changed school announcement (the scrolling notice on the class picker) rings on every
     device; a new or changed class announcement rings on the device that has that class open.
     Each version of an announcement rings once per device. The admin who typed it does not get rung. */
  const ANN_SEEN_KEY = "sssacad_ann_seen";
  function readAnnSeen() { try { return JSON.parse(lsGet(ANN_SEEN_KEY) || "null"); } catch (e) { return null; } }
  function currentAnnouncements() {
    const gate = (typeof DB !== "undefined" ? DB.get("gateAnnouncement", null) : null);
    return { gate: typeof gate === "string" ? gate.trim() : "", cls: (typeof loadAnnouncements === "function" ? loadAnnouncements() : {}) || {} };
  }
  function markAnnouncementsSeen() {
    const cur = currentAnnouncements(), snap = { gate: cur.gate, cls: {} };
    Object.keys(cur.cls).forEach((id) => { snap.cls[id] = String((cur.cls[id] && cur.cls[id].text) || "").trim(); });
    lsSet(ANN_SEEN_KEY, JSON.stringify(snap));
    if (window.NativeAlerts) window.NativeAlerts.setSeen(snap); // the phone's background listener must not ring for it either
  }
  function ringAnnouncement(title, text) {
    getCtx();
    showPopup({ icon: "📢", title: title, body: text, done: "OK, noted" });
    ringBell({ strikes: 3, gap: 1.0, speak: false, vibrate: [500, 200, 500] });
  }
  function checkAnnouncements() {
    let seen = readAnnSeen();
    if (!seen) { markAnnouncementsSeen(); return; }  // first run: record what is already there, ring only for what comes next
    const cur = currentAnnouncements();
    seen.cls = seen.cls || {};
    let alertTitle = null, alertText = "";
    if (cur.gate && cur.gate !== seen.gate) {
      seen.gate = cur.gate; alertTitle = "School Announcement"; alertText = cur.gate;
    } else if (cur.gate !== seen.gate) { seen.gate = cur.gate; } // announcement cleared: nothing to ring
    // Class announcement: only for the class this device currently has open and unlocked.
    try {
      const gateShowing = (typeof shouldShowGate === "function") ? shouldShowGate() : false;
      const classId = (typeof getCurrentClassId === "function") ? getCurrentClassId() : null;
      if (!gateShowing && classId) {
        const text = String((cur.cls[classId] && cur.cls[classId].text) || "").trim();
        if (text && text !== (seen.cls[classId] || "")) {
          const cls = (typeof loadClasses === "function" ? loadClasses() : []).find((c) => c.id === classId);
          seen.cls[classId] = text; alertTitle = "Class Announcement" + (cls ? " — " + cls.name : ""); alertText = text;
        } else if (!text) seen.cls[classId] = "";
      }
    } catch (e) { /* ignore */ }
    lsSet(ANN_SEEN_KEY, JSON.stringify(seen));
    if (alertTitle) ringAnnouncement(alertTitle, alertText);
  }

  // Called by sync.js after every merge.
  function afterSync() {
    try { receiveBuzz(); } catch (e) { /* ignore */ }
    try { checkAnnouncements(); } catch (e) { /* ignore */ }
    try { if (window.NativeAlerts) window.NativeAlerts.sync(); } catch (e) { /* ignore */ }
  }

  /* Admin card for the buzz button */
  window.buzzCardHtml = function () {
    return `
    <div class="card">
      <h2>📣 Ring All Devices</h2>
      <p style="font-size:12.5px;color:var(--muted);">Rings every phone that is open and online for 3 seconds, with the message below on screen. Phones pick it up within about 20 seconds. Use it as a quick reminder.</p>
      <label>Message (optional)</label>
      <input type="text" id="buzzTextInput" placeholder="e.g. Please come to the staff room" maxlength="120">
      <button class="btn" id="buzzAllBtn">📣 Buzz all devices (3 sec)</button>
    </div>`;
  };
  window.wireBuzzCard = function (root) {
    const b = root.querySelector("#buzzAllBtn");
    if (!b) return;
    b.addEventListener("click", () => {
      const text = (root.querySelector("#buzzTextInput") || {}).value || "";
      const r = sendBuzz(text);
      if (typeof toast === "function") toast(r.ok ? "Buzz sent — online devices will ring shortly" : r.why);
      if (r.ok) { b.disabled = true; setTimeout(() => { b.disabled = false; }, 8000); }
    });
  };

  /* ---------- Android app (Capacitor) support ----------
     When this same code is packaged as an APK with Capacitor's Local Notifications plugin, the three
     weekly alarms are scheduled with Android itself, so they ring even if the app is closed. */
  function scheduleNative() {
    try {
      const CAP = window.Capacitor;
      const LN = CAP && ((CAP.Plugins && CAP.Plugins.LocalNotifications) || (CAP.isNativePlatform && CAP.isNativePlatform() && CAP.registerPlugin ? CAP.registerPlugin("LocalNotifications") : null));
      if (!LN) return;
      const chan = LN.createChannel ? LN.createChannel({ id: "register-reminder", name: "Register reminder", importance: 5, sound: "bell", vibration: true, visibility: 1 }).catch(() => {}) : Promise.resolve();
      Promise.resolve(chan).then(() => LN.requestPermissions())
        .then(() => LN.cancel({ notifications: REMIND_HOURS.map((h) => ({ id: 9100 + h })) }).catch(() => {}))
        .then(() => LN.schedule({
          notifications: REMIND_HOURS.map((h) => ({
            id: 9100 + h, title: "St. Stephen's", body: MESSAGE,
            schedule: { on: { weekday: REMIND_DAY + 1, hour: h, minute: 0 }, allowWhileIdle: true }, // Capacitor weekdays: Sunday = 1
            sound: "bell.wav", channelId: "register-reminder"
          }))
        })).catch(() => {});
    } catch (e) { /* ignore */ }
  }

  window.Reminder = window.Alerts = { check: check, test: function () { getCtx(); fridayPopup("test"); ringBell(); }, stop: closePopup,
    afterSync: afterSync, checkAnnouncements: checkAnnouncements, markSeen: markAnnouncementsSeen, buzz: sendBuzz };

  document.addEventListener("DOMContentLoaded", () => {
    setTimeout(() => { check(); afterSync(); }, 1500);
    setInterval(check, 15000);
    document.addEventListener("visibilitychange", () => { if (!document.hidden) check(); });
    scheduleNative();
  });
})();
